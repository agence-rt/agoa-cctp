"use strict";
// Pont sécurisé entre l'interface (app/index.html) et Windows
const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("agoa", {
  native: true,
  info: () => ipcRenderer.sendSync("info"),
  loadData: () => ipcRenderer.sendSync("load-data"),
  saveData: text => ipcRenderer.send("save-data", text),
  getConfig: () => ipcRenderer.sendSync("get-config"),
  whoami: () => ipcRenderer.sendSync("whoami"),
  dbxScan: dir => ipcRenderer.invoke("dbx-scan", dir),
  dbxRead: (dir, rel) => ipcRenderer.invoke("dbx-read", dir, rel),
  mailGet: () => ipcRenderer.invoke("mail-get"),
  mailSet: (o, pass) => ipcRenderer.invoke("mail-set", o, pass),
  mailSend: msg => ipcRenderer.invoke("mail-send", msg),
  mailDraft: (to, subject, body) => ipcRenderer.invoke("mail-draft", to, subject, body),
  bkWrite: (id, text) => ipcRenderer.invoke("bk-write", id, text),
  bkList: id => ipcRenderer.invoke("bk-list", id),
  bkRead: (id, file) => ipcRenderer.invoke("bk-read", id, file),
  setConfig: patch => ipcRenderer.sendSync("set-config", patch),
  ragic: (tool, input) => ipcRenderer.invoke("ragic", tool, input),
  aiRewrite: (text, mode) => ipcRenderer.invoke("ai-rewrite", text, mode),
  aiKey: () => ipcRenderer.invoke("ai-key"),
  saveFile: (filename, bytes) => ipcRenderer.invoke("save-file", filename, bytes),
  savePDF: filename => ipcRenderer.invoke("save-pdf", filename),
  saveAs: (filename, text) => ipcRenderer.invoke("save-as", filename, text),
  writeFile: (file, text) => ipcRenderer.invoke("write-file", file, text),
  readFiles: paths => ipcRenderer.sendSync("read-files", paths),
  libState: () => ipcRenderer.sendSync("lib-state"),
  libRead: () => ipcRenderer.invoke("lib-read"),
  libWrite: (text, mtime) => ipcRenderer.invoke("lib-write", text, mtime),
  libChoose: () => ipcRenderer.invoke("lib-choose"),
  dbxFind: (ref, saved) => ipcRenderer.invoke("dbx-find", ref, saved),
  dbxChoose: () => ipcRenderer.invoke("dbx-choose"),
  dbxWrite: (dir, sub, files) => ipcRenderer.invoke("dbx-write", dir, sub, files),
  openFile: () => ipcRenderer.invoke("open-dialog"),
  checkUpdates: () => ipcRenderer.invoke("check-updates"),
  onOpenFile: cb => ipcRenderer.on("open-file", (e, name, text, file) => cb(name, text, file))
});
